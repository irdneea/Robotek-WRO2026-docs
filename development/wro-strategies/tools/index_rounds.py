#!/usr/bin/env python3
"""
Write ROUNDS.md, the English index of the simulator round records.

It reads the two ledgers (docs/*-challenge-runs/rounds.jsonl) and changes nothing else.
Run it from any folder: python3 tools/index_rounds.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
LEDGERS = (('Open Challenge', 'open'), ('Obstacle Challenge', 'obstacle'))


def folder_name(record):
    """Return the round's folder; Obstacle records keep the full path of the machine that ran them."""
    name = record.get('run') or record.get('directory') or record.get('name')
    return str(name).rstrip('/').split('/')[-1]


def day(name):
    """Return the date at the start of a folder name."""
    return f'{name[:4]}-{name[4:6]}-{name[6:8]}'


def passed(record):
    """Return the result of our acceptance check, or None when the record has no check."""
    return (record.get('validation') or {}).get('passed')


def table(records):
    """Return the lines of the table of records by day."""
    days = {}
    for record in records:
        days.setdefault(day(folder_name(record)), []).append(record)
    lines = ['| Day (from the folder name) | Records | Passed the check | Failed the check | No check |',
             '| --- | ---: | ---: | ---: | ---: |']
    total = [0, 0, 0, 0]
    for key in sorted(days):
        results = [passed(r) for r in days[key]]
        row = [len(results), results.count(True), results.count(False), results.count(None)]
        total = [a + b for a, b in zip(total, row)]
        lines.append(f'| {key} | ' + ' | '.join(str(n) for n in row) + ' |')
    lines.append('| **Total** | ' + ' | '.join(f'**{n}**' for n in total) + ' |')
    return lines


def main():
    """Write ROUNDS.md."""
    out = [
        '# Index of the simulator rounds', '',
        'Generated by [`tools/index_rounds.py`](tools/index_rounds.py) from the two ledgers. '
        'Do not edit it by hand.', '',
        'Every attempt was recorded, failed and badly prepared ones included, so these counts are '
        '**not a success rate** of the final code: they mix old and new strategies, several car models, '
        'diagnostics and experiments that were meant to find a limit. Compare rounds only when the car model, '
        'the field and the code are the same.', '',
        '"The check" is our own acceptance rule (full estimated points, no fault, no contact, a minimum margin and an '
        'observed stop). Points are estimates of a rule judge on simulator data. None is an official score.', '',
    ]
    for title, key in LEDGERS:
        base = ROOT / 'docs' / f'{key}-challenge-runs'
        records = [json.loads(line) for line in (base / 'rounds.jsonl').read_text(encoding='utf-8').splitlines()
                   if line.strip()]
        missing = [folder_name(r) for r in records if not (base / folder_name(r)).is_dir()]
        out += [f'## {title}', '',
                f'Ledger: [`rounds.jsonl`](docs/{key}-challenge-runs/rounds.jsonl). Each record has a folder with the '
                f'same name in [`docs/{key}-challenge-runs`](docs/{key}-challenge-runs).', '']
        out += table(records)
        out.append('')
        if missing:
            out += [f'Records whose folder is not here: {len(missing)}.', '']
        print(f'{key}: {len(records)} records, {len(missing)} without folder')
    (ROOT / 'ROUNDS.md').write_text('\n'.join(out), encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
